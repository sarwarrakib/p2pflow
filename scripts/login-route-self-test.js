#!/usr/bin/env node
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const index = read('public/index.html');
const login = read('public/login.html');
const loginJs = read('public/login.js');
const app = read('public/app.js');
const server = read('app-server.js');
const fail = msg => { throw new Error(`Login route self-test failed: ${msg}`); };
if (/id=["']login["']/.test(index)) fail('application index still embeds the login view');
if (!/id=["']login["']/.test(login)) fail('standalone login page is missing the login view');
if (!/src=["']\/login\.js\?v=/.test(login)) fail('standalone login page does not load login.js');
if (/window\.location\.reload\s*\(/.test(loginJs) || /location\.reload\s*\(/.test(loginJs)) fail('standalone login client contains automatic page reload logic');
if (!/redirectToLoginPage/.test(app)) fail('application does not redirect expired sessions to standalone login');
if (!/window\.location\.replace\(['"]\/login['"]\)/.test(app)) fail('logout does not land on standalone login');
if (!/pathname === '\/login'/.test(server) || !/pathname = '\/login\.html'/.test(server)) fail('server does not map /login to login.html');
console.log('Login route self-test passed.');
